/**
 * The id a room shows a member by, computed from the member's own tracking id
 * (`Subscription.uuid`): the first 128 bits of
 * `SHA-256("atmosphere.room.member:" + trackingId)`, in lowercase hex — the
 * server's `org.atmosphere.ai.RoomMemberIds.of`. A room never broadcasts a
 * tracking id (a capability: a close message naming it closes that
 * connection); it names members by this id, which cannot be turned back into
 * the tracking id. A client compares the `from` of a room's `prompt` frame with
 * its own id to tell its own prompt from another member's.
 *
 * Synchronous and dependency-free, so it works outside a secure context, where
 * `crypto.subtle` is missing.
 *
 * @returns 32 lowercase hex characters, or `''` for an empty or unknown (`'0'`) tracking id
 */
export function roomMemberId(trackingId: string | null | undefined): string {
  if (!trackingId || trackingId === '0') return '';
  const digest = sha256(utf8('atmosphere.room.member:' + trackingId));
  let hex = '';
  for (let i = 0; i < 16; i++) {
    hex += digest[i].toString(16).padStart(2, '0');
  }
  return hex;
}

function utf8(text: string): Uint8Array {
  return new TextEncoder().encode(text);
}

